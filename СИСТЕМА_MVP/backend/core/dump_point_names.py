"""Общее правило вмещения названия точки разгрузки.

Плитка точки выглядит одинаково у машиниста и у водителя, поэтому ступень
размера названия обязана считаться одинаково для обеих ролей. Вёрстка у них
своя, а это правило — общее, и живёт оно здесь, чтобы не разойтись.
"""

# Ниже этого размера название в кабине уже не прочитать мельком: экран
# грязный, взгляд короткий. Если на минимальном размере самое длинное слово
# всё равно не помещается в ширину плитки, плитка обязана дать вторую строку,
# а не срезать название нижним краем.
MIN_DUMP_NAME_FONT_PX = 14


def dump_name_size_class(name):
    """Ступень размера названия по самому длинному слову.

    Меряем именно самое длинное слово, а не длину всей строки. Перенос по
    пробелу разрешён, внутри слова — нет, поэтому в ширину плитки обязано
    поместиться самое длинное неразрывное слово целиком. «Склад негабарита»
    спокойно ложится в две строки, а вёрстку ломает одно слово «негабарита»;
    счёт по общей длине этого не различает и ошибается на обеих ролях.
    """
    words = str(name or '').split()
    longest = max((len(word) for word in words), default=0)
    if longest > 9:
        return 'is-name-long'
    if longest > 6:
        return 'is-name-medium'
    return 'is-name-short'
