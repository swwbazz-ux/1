"""Общее правило: считать ли номер техники «цифровым».

Номер из одних цифр читается издали и без крупного шрифта не теряется, поэтому
он остаётся крупным всегда и уступает только по ширине. Номер с буквами длиннее
и в ужатой карточке спорит с рисунком, поэтому он уменьшается вместе с
карточкой.

КТО ЭТО ПРИМЕНЯЕТ. Сегодня — только экран машиниста, на номере самосвала. У
водителя подпись экскаватора цифровой быть не может по построению:
users.views.driver_excavator_short_label либо возвращает номер, начинающийся на
ЭКС/ЭКГ/EX, либо сама приклеивает «ЭКС-». То есть звать это правило у водителя
не от чего — не потому, что забыли, а потому, что нечему совпасть.

Лежит в core, чтобы реализация была ОДНА, если вторая роль однажды начнёт
показывать голый номер техники. Не считать, что правило уже применяется обеими
ролями: общее здесь место, а не применение.
"""
import re

# Пробел и дефис считаем частью номера, а не буквами: «10-2» и «10 2» читаются
# так же легко, как «10».
_PLAIN_NUMBER = re.compile(r'^[\d\s\-–—]+$')


def is_plain_number(value):
    """Номер состоит только из цифр, пробелов и дефисов."""
    text = str(value or '').strip()
    return bool(text) and bool(_PLAIN_NUMBER.match(text))
